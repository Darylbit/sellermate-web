import assert from 'node:assert/strict';
import {profit,targetPrice,metrics,parseCSV,aggregate,SAMPLE} from '../js/core.js';
const near=(a,b)=>assert.ok(Math.abs(a-b)<0.011,`${a} != ${b}`);
near(profit({price:39,cost:18,fee:10,ad:5}).net,12.1);
near(profit({price:20,cost:30,fee:10,ad:5}).net,-17);
near(profit({price:20,cost:30,fee:10,ad:5}).margin,-85);
near(targetPrice({cost:20,other:5,fee:10,margin:0}),25/.9);
assert.throws(()=>targetPrice({cost:20,fee:100,margin:1}),/小於 100%/);
assert.throws(()=>profit({price:0,cost:10}),/售價/);
assert.throws(()=>profit({price:10,cost:-1}),/商品成本/);
near(metrics(1000,200,20).roas,5);
near(metrics(1000,200,20).cpa,10);
assert.equal(metrics(100,0,0).roas,null);
assert.equal(metrics(100,0,0).cpa,null);
const parsed=parseCSV('name,price,cost,orders,ad_spend\n"鞋,子",39,18,2,5\n"雙""色鞋",20,10,1,0');
assert.equal(parsed[0].name,'鞋,子');assert.equal(parsed[1].name,'雙"色鞋');
assert.equal(parsed[0].platform_fee_pct,10);
assert.throws(()=>parseCSV('name,price,cost,orders,ad_spend\na,3,2,-1,0'),/第 2 行/);
assert.throws(()=>parseCSV('name,price,cost,orders,ad_spend\na,3,2,1'),/欄位數量/);
const a=aggregate(SAMPLE);assert.equal(a.orders,405);assert.ok(a.net<a.revenue);
const zero=aggregate([{name:'未售商品',price:10,cost:4,orders:0,ad_spend:50,other_cost:0,shipping_cost:0,platform_fee_pct:10}]);near(zero.net,-50);assert.equal(zero.roas,0);assert.equal(zero.cpa,null);
console.log('PASS: 18 checks across formulas, invalid inputs, CSV and aggregation.');
